// Package connstore adapts connect.json to the interfaces the hub and the
// data plane consume.
//
// It exists so internal/hub and internal/transport describe *what* they need
// ("the account with this token", "the bindings of this Bot") without importing
// the file format. The management API keeps talking to connect.Store directly,
// because it edits the document rather than consuming it.
package connstore

import (
	"encoding/json"
	"errors"
	"sort"
	"sync"
	"time"

	"github.com/LeiSureLyYrsc/OnebotNoa/internal/connect"
	"github.com/LeiSureLyYrsc/OnebotNoa/internal/hub"
	"github.com/LeiSureLyYrsc/OnebotNoa/internal/transport"
)

// Adapter wraps one connect.Store.
type Adapter struct {
	store *connect.Store

	// state keeps the live status and last-seen time per account. Those are
	// runtime facts, so they deliberately stay out of connect.json: rewriting the
	// connection file every few seconds would churn it and turn a reviewable
	// document into a log.
	mu       sync.RWMutex
	status   map[string]string
	lastSeen map[string]time.Time
	botSeen  map[int64]time.Time
}

// New builds the adapter.
func New(store *connect.Store) *Adapter {
	return &Adapter{
		store:    store,
		status:   map[string]string{},
		lastSeen: map[string]time.Time{},
		botSeen:  map[int64]time.Time{},
	}
}

// Store exposes the underlying document for the API layer.
func (a *Adapter) Store() *connect.Store { return a.store }

// ------------------------------------------------------------------ accounts

// AccountBySelfID implements hub.ConnStore.
func (a *Adapter) AccountBySelfID(selfID string) (hub.Account, bool) {
	account, ok := a.store.AccountBySelfID(selfID)
	if !ok {
		return hub.Account{}, false
	}
	return a.toHubAccount(account), true
}

// Accounts implements hub.ConnStore.
func (a *Adapter) Accounts() []hub.Account {
	rows := a.store.ListAccounts()
	out := make([]hub.Account, 0, len(rows))
	for _, account := range rows {
		out = append(out, a.toHubAccount(account))
	}
	return out
}

func (a *Adapter) toHubAccount(account connect.Account) hub.Account {
	a.mu.RLock()
	status := a.status[account.SelfID]
	a.mu.RUnlock()
	if status == "" {
		status = "offline"
	}
	return hub.Account{
		ID: account.ID, SelfID: account.SelfID, Name: account.Name,
		Nickname: account.Nickname, Avatar: account.Avatar, Enabled: account.Enabled,
		Tags: append([]string(nil), account.Tags...), Status: status,
	}
}

// AccountByToken resolves a pre-bound per-instance token.
func (a *Adapter) AccountByToken(token string) (hub.Account, bool) {
	account, ok := a.store.AccountByToken(token)
	if !ok {
		return hub.Account{}, false
	}
	return a.toHubAccount(account), true
}

// EnsureAccount creates the account behind an approved pending connection.
func (a *Adapter) EnsureAccount(selfID, source string) (hub.Account, bool, error) {
	account, created, err := a.store.EnsureAccount(selfID, "", source)
	if err != nil {
		return hub.Account{}, false, err
	}
	return a.toHubAccount(account), created, nil
}

// SetAccountToken binds a token generated by the API.
func (a *Adapter) SetAccountToken(id int64, plain, tokenHash, hint string) error {
	return a.store.SetAccountToken(id, plain, tokenHash, hint)
}

// AccountToken exposes a plaintext token (the WebUI shows it again when the
// operator asks; it is already stored sealed for the dial path).
func (a *Adapter) AccountToken(id int64) (string, error) {
	return a.store.AccountToken(id)
}

// PersistAccountState records the live state in memory, not on disk.
func (a *Adapter) PersistAccountState(selfID, status string) error {
	a.mu.Lock()
	a.status[selfID] = status
	a.lastSeen[selfID] = time.Now()
	a.mu.Unlock()
	return nil
}

// LastSeen reports when an account was last connected.
func (a *Adapter) LastSeen(selfID string) (time.Time, bool) {
	a.mu.RLock()
	defer a.mu.RUnlock()
	at, ok := a.lastSeen[selfID]
	return at, ok
}

// LiveStatus reports the in-memory status of an account.
func (a *Adapter) LiveStatus(selfID string) string {
	a.mu.RLock()
	defer a.mu.RUnlock()
	if status := a.status[selfID]; status != "" {
		return status
	}
	return "offline"
}

